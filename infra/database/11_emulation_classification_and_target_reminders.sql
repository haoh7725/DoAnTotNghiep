CREATE TABLE IF NOT EXISTS nckh.quy_che_xep_loai_thi_dua (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nam_hoc_id bigint NOT NULL REFERENCES nckh.nam_hoc(id) ON DELETE CASCADE,
    ten_xep_loai varchar(100) NOT NULL,
    ty_le_toi_thieu numeric(7,2) NOT NULL CHECK (ty_le_toi_thieu >= 0),
    thu_tu integer NOT NULL DEFAULT 0 CHECK (thu_tu >= 0),
    CONSTRAINT uq_quy_che_xep_loai_ten UNIQUE (nam_hoc_id, ten_xep_loai),
    CONSTRAINT uq_quy_che_xep_loai_nguong UNIQUE (nam_hoc_id, ty_le_toi_thieu)
);
