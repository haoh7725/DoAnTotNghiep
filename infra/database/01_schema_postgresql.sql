-- Lock the quota row before computing the sum, so concurrent allocations cannot overbook it.
CREATE FUNCTION kiem_tra_phan_bo() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    muc_giao INTEGER;
    da_phan_bo BIGINT;
BEGIN
    SELECT so_bai_duoc_giao INTO muc_giao
    FROM chi_tieu_nckh WHERE id = NEW.chi_tieu_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Chi tieu % khong ton tai', NEW.chi_tieu_id;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        SELECT COALESCE(SUM(so_bai_phan_bo), 0) INTO da_phan_bo
        FROM phan_bo_chi_tieu
        WHERE chi_tieu_id = NEW.chi_tieu_id AND id <> OLD.id;
    ELSE
        SELECT COALESCE(SUM(so_bai_phan_bo), 0) INTO da_phan_bo
        FROM phan_bo_chi_tieu WHERE chi_tieu_id = NEW.chi_tieu_id;
    END IF;
    IF da_phan_bo + NEW.so_bai_phan_bo > muc_giao THEN
        RAISE EXCEPTION 'Tong phan bo vuot chi tieu duoc giao (%)', muc_giao;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER tr_kiem_tra_phan_bo
BEFORE INSERT OR UPDATE OF chi_tieu_id, so_bai_phan_bo ON phan_bo_chi_tieu
FOR EACH ROW EXECUTE FUNCTION kiem_tra_phan_bo();

CREATE FUNCTION kiem_tra_giam_chi_tieu() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.so_bai_duoc_giao < (
        SELECT COALESCE(SUM(so_bai_phan_bo), 0)
        FROM phan_bo_chi_tieu WHERE chi_tieu_id = NEW.id
    ) THEN
        RAISE EXCEPTION 'Chi tieu moi nho hon tong da phan bo';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER tr_kiem_tra_giam_chi_tieu
BEFORE UPDATE OF so_bai_duoc_giao ON chi_tieu_nckh
FOR EACH ROW EXECUTE FUNCTION kiem_tra_giam_chi_tieu();

