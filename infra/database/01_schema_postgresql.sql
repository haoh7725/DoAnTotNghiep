SELECT k.id, k.giang_vien_id, k.nam_hoc_id, k.lan_danh_gia,
       k.trang_thai, k.xep_loai,
       COALESCE(SUM(c.gia_tri_quy_doi) FILTER (WHERE c.don_vi = 'GIO'), 0) AS tong_gio,
       COALESCE(SUM(c.gia_tri_quy_doi) FILTER (WHERE c.don_vi = 'DIEM'), 0) AS tong_diem
FROM ket_qua_danh_gia AS k
LEFT JOIN chi_tiet_quy_doi AS c ON c.ket_qua_id = k.id
GROUP BY k.id;

