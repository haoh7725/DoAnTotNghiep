    thu_tu_tac_gia INTEGER NOT NULL,
    PRIMARY KEY (san_pham_id, giang_vien_id),
    UNIQUE (san_pham_id, thu_tu_tac_gia),
    CONSTRAINT ck_tham_gia_thu_tu CHECK (thu_tu_tac_gia > 0)
);

CREATE TABLE noi_dung_ke_hoach_san_pham (
    noi_dung_id BIGINT NOT NULL REFERENCES noi_dung_ke_hoach(id),
    san_pham_id BIGINT NOT NULL REFERENCES san_pham_khoa_hoc(id),
    PRIMARY KEY (noi_dung_id, san_pham_id)
);

CREATE TABLE minh_chung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT NOT NULL REFERENCES san_pham_khoa_hoc(id),
    nguoi_tai_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    ten_tai_lieu VARCHAR(255) NOT NULL,
    khoa_luu_tru VARCHAR(512) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    kich_thuoc BIGINT NOT NULL,
    sha256 CHAR(64),
    tai_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_minh_chung_kich_thuoc CHECK (kich_thuoc >= 0)
);

CREATE TABLE lich_su_xet_duyet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT NOT NULL,
    nguoi_thuc_hien_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    phien_ban INTEGER NOT NULL,
    hanh_dong VARCHAR(30) NOT NULL,
    nhan_xet TEXT,
    trang_thai_truoc VARCHAR(20) NOT NULL,
    trang_thai_sau VARCHAR(20) NOT NULL,
    thoi_diem TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lich_su_duyet_phien_ban FOREIGN KEY (san_pham_id, phien_ban)
