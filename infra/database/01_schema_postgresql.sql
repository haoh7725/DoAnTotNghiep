-- PostgreSQL 15+; run on an empty database (for example, nckh_v02).
-- All names are kept close to the SQL Server v02 schema. No JSON/NoSQL columns.
CREATE SCHEMA IF NOT EXISTS nckh;
SET search_path TO nckh, public;

CREATE TABLE khoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_khoa VARCHAR(30) NOT NULL UNIQUE,
    ten_khoa VARCHAR(200) NOT NULL
);

CREATE TABLE bo_mon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    khoa_id BIGINT NOT NULL REFERENCES khoa(id),
    ma_bo_mon VARCHAR(30) NOT NULL UNIQUE,
    ten_bo_mon VARCHAR(200) NOT NULL,
    UNIQUE (id, khoa_id)
);

CREATE TABLE nam_hoc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_nam_hoc VARCHAR(20) NOT NULL UNIQUE,
    ngay_bat_dau DATE NOT NULL,
    ngay_ket_thuc DATE NOT NULL,
    CONSTRAINT ck_nam_hoc_ngay CHECK (ngay_ket_thuc >= ngay_bat_dau)
);

CREATE TABLE tai_khoan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_dang_nhap VARCHAR(100) NOT NULL UNIQUE,
    mat_khau_hash VARCHAR(255) NOT NULL,
    ho_ten VARCHAR(200) NOT NULL,
    email VARCHAR(254),
    trang_thai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tai_khoan_trang_thai CHECK (trang_thai IN ('HOAT_DONG', 'KHOA'))
);
CREATE UNIQUE INDEX uq_tai_khoan_email ON tai_khoan (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE phan_quyen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tai_khoan_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    vai_tro VARCHAR(30) NOT NULL,
    pham_vi VARCHAR(20) NOT NULL,
    khoa_id BIGINT REFERENCES khoa(id),
    bo_mon_id BIGINT,
    CONSTRAINT ck_phan_quyen_vai_tro CHECK (vai_tro IN
        ('GIANG_VIEN', 'TRUONG_BO_MON', 'TRUONG_KHOA', 'PHONG_QLKH', 'BAN_GIAM_HIEU', 'QUAN_TRI')),
    CONSTRAINT ck_phan_quyen_pham_vi CHECK (
        (pham_vi = 'CA_NHAN' AND khoa_id IS NULL AND bo_mon_id IS NULL) OR
        (pham_vi = 'BO_MON' AND khoa_id IS NOT NULL AND bo_mon_id IS NOT NULL) OR
        (pham_vi = 'KHOA' AND khoa_id IS NOT NULL AND bo_mon_id IS NULL) OR
        (pham_vi = 'TOAN_TRUONG' AND khoa_id IS NULL AND bo_mon_id IS NULL)),
    CONSTRAINT ck_phan_quyen_vai_tro_pham_vi CHECK (
        (vai_tro = 'GIANG_VIEN' AND pham_vi = 'CA_NHAN') OR
        (vai_tro = 'TRUONG_BO_MON' AND pham_vi = 'BO_MON') OR
        (vai_tro = 'TRUONG_KHOA' AND pham_vi = 'KHOA') OR
        (vai_tro IN ('PHONG_QLKH', 'BAN_GIAM_HIEU', 'QUAN_TRI') AND pham_vi = 'TOAN_TRUONG')),
    CONSTRAINT fk_phan_quyen_bo_mon FOREIGN KEY (bo_mon_id, khoa_id)
        REFERENCES bo_mon(id, khoa_id),
    CONSTRAINT uq_phan_quyen_pham_vi UNIQUE NULLS NOT DISTINCT
        (tai_khoan_id, vai_tro, pham_vi, khoa_id, bo_mon_id)
);

CREATE TABLE giang_vien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bo_mon_id BIGINT NOT NULL REFERENCES bo_mon(id),
    tai_khoan_id BIGINT NOT NULL UNIQUE REFERENCES tai_khoan(id),
    ma_giang_vien VARCHAR(30) NOT NULL UNIQUE,
    ho_ten VARCHAR(200) NOT NULL,
    ngay_sinh DATE,
    gioi_tinh VARCHAR(20),
    email VARCHAR(254),
    so_dien_thoai VARCHAR(30),
    hoc_ham VARCHAR(100),
    hoc_vi VARCHAR(100),
    chuc_vu VARCHAR(100)
);

CREATE TABLE ly_lich_khoa_hoc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giang_vien_id BIGINT NOT NULL UNIQUE REFERENCES giang_vien(id),
    chuyen_mon TEXT,
    linh_vuc_nghien_cuu TEXT,
    huong_nghien_cuu TEXT,
    tom_tat_hoat_dong TEXT,
    cap_nhat_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE loai_san_pham (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_loai VARCHAR(30) NOT NULL UNIQUE,
    ten_loai VARCHAR(100) NOT NULL
);

CREATE TABLE ke_hoach_nckh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giang_vien_id BIGINT NOT NULL REFERENCES giang_vien(id),
    nam_hoc_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    so_bai_cam_ket INTEGER NOT NULL DEFAULT 0,
    ngay_lap DATE NOT NULL,
    trang_thai VARCHAR(20) NOT NULL DEFAULT 'NHAP',
    han_hoan_thanh DATE,
    UNIQUE (giang_vien_id, nam_hoc_id),
    CONSTRAINT ck_ke_hoach_so_bai CHECK (so_bai_cam_ket >= 0),
    CONSTRAINT ck_ke_hoach_trang_thai CHECK (trang_thai IN ('NHAP', 'DA_DANG_KY'))
);

CREATE TABLE noi_dung_ke_hoach (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ke_hoach_id BIGINT NOT NULL REFERENCES ke_hoach_nckh(id),
    loai_san_pham_id BIGINT NOT NULL REFERENCES loai_san_pham(id),
    ten_noi_dung VARCHAR(500) NOT NULL,
    so_luong_cam_ket INTEGER NOT NULL DEFAULT 1,
    han_hoan_thanh DATE,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHUA_THUC_HIEN',
    ket_qua TEXT,
    kho_khan_de_xuat TEXT,
    cap_nhat_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_noi_dung_so_luong CHECK (so_luong_cam_ket > 0),
    CONSTRAINT ck_noi_dung_trang_thai CHECK (trang_thai IN
        ('CHUA_THUC_HIEN', 'DANG_THUC_HIEN', 'DA_THUC_HIEN'))
);

CREATE TABLE lich_su_tien_do (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    noi_dung_id BIGINT NOT NULL REFERENCES noi_dung_ke_hoach(id),
    nguoi_cap_nhat_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    trang_thai VARCHAR(30) NOT NULL,
    ket_qua TEXT,
    kho_khan_de_xuat TEXT,
    thoi_diem TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_lich_su_tien_do_trang_thai CHECK (trang_thai IN
        ('CHUA_THUC_HIEN', 'DANG_THUC_HIEN', 'DA_THUC_HIEN'))
);

CREATE TABLE chi_tieu_nckh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    khoa_id BIGINT NOT NULL REFERENCES khoa(id),
    nam_hoc_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    so_bai_duoc_giao INTEGER NOT NULL,
    han_hoan_thanh DATE,
    UNIQUE (khoa_id, nam_hoc_id),
    UNIQUE (id, khoa_id),
    CONSTRAINT ck_chi_tieu_so_bai CHECK (so_bai_duoc_giao >= 0)
);

CREATE TABLE phan_bo_chi_tieu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chi_tieu_id BIGINT NOT NULL,
    khoa_id BIGINT NOT NULL,
    bo_mon_id BIGINT NOT NULL,
    so_bai_phan_bo INTEGER NOT NULL,
    ngay_phan_bo DATE NOT NULL,
    UNIQUE (chi_tieu_id, bo_mon_id),
    CONSTRAINT fk_phan_bo_chi_tieu_khoa FOREIGN KEY (chi_tieu_id, khoa_id)
        REFERENCES chi_tieu_nckh(id, khoa_id),
    CONSTRAINT fk_phan_bo_chi_tieu_bo_mon FOREIGN KEY (bo_mon_id, khoa_id)
        REFERENCES bo_mon(id, khoa_id),
    CONSTRAINT ck_phan_bo_so_bai CHECK (so_bai_phan_bo >= 0)
);

CREATE TABLE dinh_muc_nckh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giang_vien_id BIGINT NOT NULL REFERENCES giang_vien(id),
    nam_hoc_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    so_gio_dinh_muc NUMERIC(12,4) NOT NULL,
    can_cu TEXT,
    UNIQUE (giang_vien_id, nam_hoc_id),
    CONSTRAINT ck_dinh_muc_so_gio CHECK (so_gio_dinh_muc >= 0)
);

CREATE TABLE san_pham_khoa_hoc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loai_san_pham_id BIGINT NOT NULL REFERENCES loai_san_pham(id),
    nam_hoc_ghi_nhan_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    nguoi_tao_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    ma_san_pham VARCHAR(40) NOT NULL UNIQUE,
    ten_san_pham VARCHAR(500) NOT NULL,
    nam_cong_bo SMALLINT,
    thong_tin_cong_bo TEXT,
    doi VARCHAR(255),
    isbn VARCHAR(30),
    issn VARCHAR(20),
    ten_tap_chi_hoi_nghi VARCHAR(300),
    chi_so_tap_chi VARCHAR(100),
    phan_loai_tap_chi VARCHAR(100),
    diem_cong_trinh NUMERIC(10,4),
    linh_vuc_nghien_cuu VARCHAR(300),
    nha_xuat_ban VARCHAR(300),
    cap_de_tai VARCHAR(100),
    don_vi_chu_tri VARCHAR(300),
    muc_tieu_de_tai TEXT,
    noi_dung_de_tai TEXT,
    ket_qua_du_kien TEXT,
    so_chung_nhan VARCHAR(100),
    co_quan_cap VARCHAR(300),
    ngay_bat_dau DATE,
    ngay_ket_thuc DATE,
    ngay_nop DATE,
    ngay_xuat_ban DATE,
    trang_thai_bai_bao VARCHAR(30),
    trang_thai_duyet VARCHAR(20) NOT NULL DEFAULT 'NHAP',
    phien_ban INTEGER NOT NULL DEFAULT 1,
    UNIQUE (id, loai_san_pham_id),
    UNIQUE (id, nam_hoc_ghi_nhan_id),
    CONSTRAINT ck_san_pham_phien_ban CHECK (phien_ban > 0),
    CONSTRAINT ck_san_pham_nam_cong_bo CHECK (nam_cong_bo IS NULL OR nam_cong_bo BETWEEN 1900 AND 2200),
    CONSTRAINT ck_san_pham_ngay CHECK (ngay_ket_thuc IS NULL OR ngay_bat_dau IS NULL
        OR ngay_ket_thuc >= ngay_bat_dau),
    CONSTRAINT ck_san_pham_diem CHECK (diem_cong_trinh IS NULL OR diem_cong_trinh >= 0),
    CONSTRAINT ck_san_pham_trang_thai_bai_bao CHECK (trang_thai_bai_bao IS NULL OR
        trang_thai_bai_bao IN ('DANG_VIET', 'DANG_PHAN_BIEN', 'DA_NHAN_XET', 'DA_XUAT_BAN')),
    CONSTRAINT ck_san_pham_trang_thai_duyet CHECK (trang_thai_duyet IN
        ('NHAP', 'CHO_DUYET', 'CAN_BO_SUNG', 'DA_DUYET', 'TU_CHOI'))
);
CREATE UNIQUE INDEX uq_san_pham_doi ON san_pham_khoa_hoc(lower(doi)) WHERE doi IS NOT NULL;

CREATE TABLE san_pham_phien_ban (
    san_pham_id BIGINT NOT NULL REFERENCES san_pham_khoa_hoc(id),
