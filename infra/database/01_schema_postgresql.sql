    nguoi_cap_nhat_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    ghi_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    loai_san_pham_id BIGINT NOT NULL REFERENCES loai_san_pham(id),
    nam_hoc_ghi_nhan_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    ma_san_pham VARCHAR(40) NOT NULL,
    ten_san_pham VARCHAR(500) NOT NULL,
    nam_cong_bo SMALLINT,
    thong_tin_cong_bo TEXT,
    doi VARCHAR(255),
    isbn VARCHAR(30),
    issn VARCHAR(20),
    ten_tap_chi_hoi_nghi VARCHAR(300),
    chi_so_tap_chi VARCHAR(100),
    phan_loai_tap_chi VARCHAR(100),
    diem_cong_trinh NUMERIC(10,4),
    linh_vuc_nghien_cuu VARCHAR(300),
