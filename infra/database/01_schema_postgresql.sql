    CONSTRAINT ck_lich_su_duyet_phien_ban CHECK (phien_ban > 0),
    CONSTRAINT ck_lich_su_duyet_hanh_dong CHECK (hanh_dong IN
        ('GUI_DUYET', 'YEU_CAU_BO_SUNG', 'PHE_DUYET', 'TU_CHOI'))
);

CREATE TABLE phan_hoi_san_pham (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT NOT NULL REFERENCES san_pham_khoa_hoc(id),
    nguoi_gui_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    noi_dung TEXT NOT NULL,
    thoi_diem TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE thong_bao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_nhan_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    noi_dung_id BIGINT REFERENCES noi_dung_ke_hoach(id),
    phan_hoi_id BIGINT REFERENCES phan_hoi_san_pham(id),
    ke_hoach_id BIGINT REFERENCES ke_hoach_nckh(id),
    san_pham_id BIGINT REFERENCES san_pham_khoa_hoc(id),
    loai VARCHAR(20) NOT NULL,
    noi_dung TEXT NOT NULL,
    khoa_chong_trung VARCHAR(191) NOT NULL,
    kenh VARCHAR(20) NOT NULL DEFAULT 'IN_APP',
    trang_thai_gui VARCHAR(20) NOT NULL DEFAULT 'CHO_GUI',
    so_lan_thu INTEGER NOT NULL DEFAULT 0,
    gui_sau TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    giu_den TIMESTAMPTZ,
    da_gui_luc TIMESTAMPTZ,
    da_doc_luc TIMESTAMPTZ,
    loi_gui TEXT,
    UNIQUE (nguoi_nhan_id, kenh, khoa_chong_trung),
    CONSTRAINT ck_thong_bao_so_lan_thu CHECK (so_lan_thu >= 0),
    CONSTRAINT ck_thong_bao_loai CHECK (loai IN ('NHAC_HAN', 'QUA_HAN', 'PHAN_HOI', 'HE_THONG')),
    CONSTRAINT ck_thong_bao_kenh CHECK (kenh IN ('IN_APP', 'EMAIL', 'PUSH')),
    CONSTRAINT ck_thong_bao_trang_thai CHECK (trang_thai_gui IN ('CHO_GUI', 'DANG_GUI', 'DA_GUI', 'LOI'))
);

CREATE TABLE quy_dinh_quy_doi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loai_san_pham_id BIGINT NOT NULL REFERENCES loai_san_pham(id),
    ma_quy_dinh VARCHAR(50) NOT NULL,
    phien_ban INTEGER NOT NULL,
    ten_quy_dinh VARCHAR(300) NOT NULL,
    mo_ta_dieu_kien TEXT NOT NULL,
    muc_quy_doi NUMERIC(14,4) NOT NULL,
    don_vi VARCHAR(10) NOT NULL,
    mo_ta_quy_tac_tac_gia TEXT NOT NULL,
    hieu_luc_tu DATE NOT NULL,
    hieu_luc_den DATE,
    van_ban_can_cu VARCHAR(512) NOT NULL,
    UNIQUE (ma_quy_dinh, phien_ban),
    UNIQUE (id, loai_san_pham_id),
    UNIQUE (id, loai_san_pham_id, don_vi),
    CONSTRAINT ck_quy_dinh_phien_ban CHECK (phien_ban > 0),
    CONSTRAINT ck_quy_dinh_muc CHECK (muc_quy_doi >= 0),
    CONSTRAINT ck_quy_dinh_hieu_luc CHECK (hieu_luc_den IS NULL OR hieu_luc_den >= hieu_luc_tu),
    CONSTRAINT ck_quy_dinh_don_vi CHECK (don_vi IN ('GIO', 'DIEM'))
);

CREATE TABLE tieu_chi_quy_doi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quy_dinh_id BIGINT NOT NULL REFERENCES quy_dinh_quy_doi(id),
    truong_du_lieu VARCHAR(40) NOT NULL,
    toan_tu VARCHAR(12) NOT NULL,
    gia_tri_chuoi VARCHAR(300),
    gia_tri_so NUMERIC(14,4),
    CONSTRAINT ck_tieu_chi_truong CHECK (truong_du_lieu IN
        ('CHI_SO_TAP_CHI', 'PHAN_LOAI_TAP_CHI', 'CAP_DE_TAI', 'DIEM_CONG_TRINH', 'NAM_CONG_BO')),
    CONSTRAINT ck_tieu_chi_toan_tu CHECK (toan_tu IN ('BANG', 'KHAC', 'TU', 'DEN')),
    CONSTRAINT ck_tieu_chi_gia_tri CHECK ((gia_tri_chuoi IS NOT NULL)::INTEGER +
        (gia_tri_so IS NOT NULL)::INTEGER = 1),
    CONSTRAINT ck_tieu_chi_kieu CHECK (
        (truong_du_lieu IN ('CHI_SO_TAP_CHI', 'PHAN_LOAI_TAP_CHI', 'CAP_DE_TAI')
            AND gia_tri_chuoi IS NOT NULL AND toan_tu IN ('BANG', 'KHAC')) OR
        (truong_du_lieu IN ('DIEM_CONG_TRINH', 'NAM_CONG_BO') AND gia_tri_so IS NOT NULL))
);

CREATE TABLE he_so_tac_gia_quy_doi (
    quy_dinh_id BIGINT NOT NULL REFERENCES quy_dinh_quy_doi(id),
    vai_tro_tac_gia VARCHAR(100) NOT NULL,
    he_so NUMERIC(12,6) NOT NULL,
    PRIMARY KEY (quy_dinh_id, vai_tro_tac_gia),
    CONSTRAINT ck_he_so_tac_gia CHECK (he_so >= 0)
);

CREATE TABLE ket_qua_danh_gia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giang_vien_id BIGINT NOT NULL REFERENCES giang_vien(id),
    nam_hoc_id BIGINT NOT NULL REFERENCES nam_hoc(id),
    lan_danh_gia INTEGER NOT NULL DEFAULT 1,
    nguoi_danh_gia_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    trang_thai VARCHAR(10) NOT NULL DEFAULT 'NHAP',
    xep_loai VARCHAR(100),
    can_cu_xep_loai TEXT,
    ma_giang_vien_anh_chup VARCHAR(30) NOT NULL,
    ho_ten_giang_vien_anh_chup VARCHAR(200) NOT NULL,
    bo_mon_id_anh_chup BIGINT NOT NULL REFERENCES bo_mon(id),
    hoc_ham_anh_chup VARCHAR(100),
    hoc_vi_anh_chup VARCHAR(100),
    ngay_danh_gia TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (giang_vien_id, nam_hoc_id, lan_danh_gia),
    UNIQUE (id, giang_vien_id, nam_hoc_id),
    CONSTRAINT ck_danh_gia_lan CHECK (lan_danh_gia > 0),
    CONSTRAINT ck_danh_gia_trang_thai CHECK (trang_thai IN ('NHAP', 'CHOT')),
    CONSTRAINT ck_danh_gia_chot CHECK (trang_thai <> 'CHOT' OR
        (xep_loai IS NOT NULL AND can_cu_xep_loai IS NOT NULL))
);

CREATE TABLE chi_tiet_quy_doi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ket_qua_id BIGINT NOT NULL,
    giang_vien_id BIGINT NOT NULL,
    nam_hoc_id BIGINT NOT NULL,
    san_pham_id BIGINT NOT NULL,
    loai_san_pham_id BIGINT NOT NULL,
    quy_dinh_id BIGINT NOT NULL,
    gia_tri_goc NUMERIC(14,4) NOT NULL,
    he_so_tac_gia NUMERIC(12,6) NOT NULL,
    gia_tri_quy_doi NUMERIC(14,4) NOT NULL,
    don_vi VARCHAR(10) NOT NULL,
    can_cu_tinh TEXT NOT NULL,
    UNIQUE (ket_qua_id, san_pham_id, don_vi),
    CONSTRAINT fk_chi_tiet_danh_gia FOREIGN KEY (ket_qua_id, giang_vien_id, nam_hoc_id)
        REFERENCES ket_qua_danh_gia(id, giang_vien_id, nam_hoc_id),
    CONSTRAINT fk_chi_tiet_tac_gia FOREIGN KEY (san_pham_id, giang_vien_id)
        REFERENCES tham_gia_san_pham(san_pham_id, giang_vien_id),
    CONSTRAINT fk_chi_tiet_loai FOREIGN KEY (san_pham_id, loai_san_pham_id)
        REFERENCES san_pham_khoa_hoc(id, loai_san_pham_id),
    CONSTRAINT fk_chi_tiet_nam FOREIGN KEY (san_pham_id, nam_hoc_id)
        REFERENCES san_pham_khoa_hoc(id, nam_hoc_ghi_nhan_id),
    CONSTRAINT fk_chi_tiet_quy_dinh FOREIGN KEY (quy_dinh_id, loai_san_pham_id, don_vi)
        REFERENCES quy_dinh_quy_doi(id, loai_san_pham_id, don_vi),
    CONSTRAINT ck_chi_tiet_gia_tri CHECK (gia_tri_goc >= 0 AND he_so_tac_gia >= 0
        AND gia_tri_quy_doi >= 0),
    CONSTRAINT ck_chi_tiet_don_vi CHECK (don_vi IN ('GIO', 'DIEM'))
);

CREATE TABLE bao_cao_xuat (
