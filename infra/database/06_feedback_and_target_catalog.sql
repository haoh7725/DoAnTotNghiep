CREATE UNIQUE INDEX IF NOT EXISTS ux_chi_tieu_khoa_nam_danh_muc ON nckh.chi_tieu_nckh(khoa_id, nam_hoc_id, COALESCE(tap_chi_hoi_nghi_id, 0));
