CREATE TABLE IF NOT EXISTS nckh.phan_hoi_san_pham_ung_dung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT NOT NULL REFERENCES nckh.san_pham(id) ON DELETE CASCADE,
    nguoi_gui_id BIGINT NOT NULL REFERENCES nckh.tai_khoan(id),
    noi_dung TEXT NOT NULL CHECK (length(btrim(noi_dung)) BETWEEN 1 AND 2000),
    thoi_diem TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_phan_hoi_san_pham_ung_dung ON nckh.phan_hoi_san_pham_ung_dung(san_pham_id, thoi_diem);

