BEGIN;
CREATE TABLE IF NOT EXISTS nckh.de_nghi_tien_do_bai_bao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id bigint NOT NULL REFERENCES nckh.san_pham(id) ON DELETE CASCADE,
    nguoi_de_nghi_id bigint NOT NULL REFERENCES nckh.tai_khoan(id),
    tu_trang_thai varchar(30) NOT NULL,
    den_trang_thai varchar(30) NOT NULL,
    minh_chung_id bigint NOT NULL REFERENCES nckh.minh_chung_san_pham(id),
    vai_tro_duyet varchar(30) NOT NULL,
    ngay_cong_bo date,
    thong_tin_xuat_ban varchar(500),
    ghi_chu_de_nghi varchar(1000),
    trang_thai varchar(20) NOT NULL DEFAULT 'CHO_DUYET' CHECK (trang_thai IN ('CHO_DUYET','DA_DUYET','TRA_LAI')),
    nguoi_xet_duyet_id bigint REFERENCES nckh.tai_khoan(id),
    ghi_chu_xet_duyet varchar(1000),
    de_nghi_luc timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    xet_duyet_luc timestamptz,
    CHECK (tu_trang_thai IN ('DANG_VIET','DANG_PHAN_BIEN','DA_NHAN_XET','DA_XUAT_BAN')),
    CHECK (den_trang_thai IN ('DANG_PHAN_BIEN','DA_NHAN_XET','DA_XUAT_BAN')),
    CHECK (vai_tro_duyet IN ('TRUONG_BO_MON','TRUONG_KHOA')),
    CHECK (den_trang_thai <> 'DA_XUAT_BAN' OR ngay_cong_bo IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_de_nghi_tien_do_dang_cho
    ON nckh.de_nghi_tien_do_bai_bao(san_pham_id) WHERE trang_thai='CHO_DUYET';
CREATE INDEX IF NOT EXISTS ix_de_nghi_tien_do_vai_tro_trang_thai
    ON nckh.de_nghi_tien_do_bai_bao(vai_tro_duyet,trang_thai,de_nghi_luc);
COMMIT;
