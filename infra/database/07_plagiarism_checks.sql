SET search_path TO nckh, public;

CREATE TABLE IF NOT EXISTS kiem_tra_tuong_dong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT NOT NULL REFERENCES san_pham(id) ON DELETE CASCADE,
    minh_chung_id BIGINT REFERENCES minh_chung_san_pham(id) ON DELETE SET NULL,
    nha_cung_cap VARCHAR(30) NOT NULL DEFAULT 'COPYLEAKS',
    external_scan_id VARCHAR(100),
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_XU_LY',
    ty_le_tuong_dong NUMERIC(5,2),
    so_nguon_trung INTEGER,
    tong_so_tu INTEGER,
    so_credit INTEGER,
    file_hash VARCHAR(64) NOT NULL,
    report_url TEXT,
    report_object_key VARCHAR(500),
    loi TEXT,
    nguoi_yeu_cau_id BIGINT NOT NULL REFERENCES tai_khoan(id),
    da_dong_y_gui_ben_thu_ba BOOLEAN NOT NULL DEFAULT FALSE,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    bat_dau_luc TIMESTAMPTZ,
    hoan_thanh_luc TIMESTAMPTZ,
    CONSTRAINT ck_kiem_tra_tuong_dong_trang_thai CHECK (trang_thai IN
        ('CHO_XU_LY','DANG_GUI','DANG_KIEM_TRA','HOAN_THANH','THAT_BAI','DA_HUY')),
    CONSTRAINT ck_kiem_tra_tuong_dong_ty_le CHECK
        (ty_le_tuong_dong IS NULL OR ty_le_tuong_dong BETWEEN 0 AND 100),
    CONSTRAINT ck_kiem_tra_tuong_dong_so_lieu CHECK
        ((so_nguon_trung IS NULL OR so_nguon_trung >= 0) AND
         (tong_so_tu IS NULL OR tong_so_tu >= 0) AND
         (so_credit IS NULL OR so_credit >= 0))
);

CREATE INDEX IF NOT EXISTS ix_kiem_tra_tuong_dong_san_pham
    ON kiem_tra_tuong_dong (san_pham_id, tao_luc DESC);
CREATE INDEX IF NOT EXISTS ix_kiem_tra_tuong_dong_minh_chung
    ON kiem_tra_tuong_dong (minh_chung_id, tao_luc DESC);
CREATE INDEX IF NOT EXISTS ix_kiem_tra_tuong_dong_dang_xu_ly
    ON kiem_tra_tuong_dong (trang_thai)
    WHERE trang_thai IN ('CHO_XU_LY','DANG_GUI','DANG_KIEM_TRA');
CREATE UNIQUE INDEX IF NOT EXISTS ux_kiem_tra_tuong_dong_external_scan
    ON kiem_tra_tuong_dong (nha_cung_cap, external_scan_id)
    WHERE external_scan_id IS NOT NULL;
