CREATE TABLE IF NOT EXISTS nckh.phan_cong_chi_tieu_giang_vien (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phan_bo_bo_mon_id bigint NOT NULL REFERENCES nckh.phan_bo_chi_tieu(id) ON DELETE CASCADE,
    giang_vien_id bigint NOT NULL REFERENCES nckh.giang_vien(id) ON DELETE RESTRICT,
    so_bai_phan_cong integer NOT NULL CHECK (so_bai_phan_cong > 0),
    ngay_phan_cong date NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ux_phan_cong_chi_tieu_gv UNIQUE (phan_bo_bo_mon_id, giang_vien_id)
);

CREATE OR REPLACE FUNCTION nckh.kiem_tra_tong_phan_cong_giang_vien() RETURNS trigger AS $$
DECLARE gioi_han integer; tong integer;
BEGIN
    SELECT so_bai_phan_bo INTO gioi_han FROM nckh.phan_bo_chi_tieu WHERE id = NEW.phan_bo_bo_mon_id FOR UPDATE;
    SELECT COALESCE(SUM(so_bai_phan_cong), 0) INTO tong FROM nckh.phan_cong_chi_tieu_giang_vien
      WHERE phan_bo_bo_mon_id = NEW.phan_bo_bo_mon_id AND id <> COALESCE(NEW.id, -1);
    IF tong + NEW.so_bai_phan_cong > gioi_han THEN RAISE EXCEPTION 'Tổng giao giảng viên vượt chỉ tiêu bộ môn'; END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_kiem_tra_tong_phan_cong_gv ON nckh.phan_cong_chi_tieu_giang_vien;
CREATE TRIGGER trg_kiem_tra_tong_phan_cong_gv BEFORE INSERT OR UPDATE ON nckh.phan_cong_chi_tieu_giang_vien
FOR EACH ROW EXECUTE FUNCTION nckh.kiem_tra_tong_phan_cong_giang_vien();
