
CREATE TABLE IF NOT EXISTS nckh.danh_muc_tap_chi_hoi_nghi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten VARCHAR(300) NOT NULL,
    loai VARCHAR(20) NOT NULL,
    issn VARCHAR(30),
    chi_so VARCHAR(100),
    phan_loai VARCHAR(100),
    ghi_chu TEXT,
    tao_luc TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_danh_muc_tap_chi_hoi_nghi_loai
        CHECK (loai IN ('TAP_CHI', 'HOI_NGHI')),

    CONSTRAINT ck_danh_muc_tap_chi_hoi_nghi_ten
        CHECK (length(btrim(ten)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_danh_muc_tap_chi_hoi_nghi_ten_loai
ON nckh.danh_muc_tap_chi_hoi_nghi (lower(btrim(ten)), loai);
