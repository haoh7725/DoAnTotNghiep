CREATE TABLE IF NOT EXISTS nckh.lich_su_ke_hoach (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ke_hoach_id BIGINT NOT NULL REFERENCES nckh.ke_hoach_nckh(id),
    nguoi_thuc_hien_id BIGINT NOT NULL REFERENCES nckh.tai_khoan(id),
    trang_thai_cu VARCHAR(30) NOT NULL,
    trang_thai_moi VARCHAR(30) NOT NULL,
    ly_do VARCHAR(1000) NOT NULL,
    thoi_diem TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_lich_su_ke_hoach
    ON nckh.lich_su_ke_hoach(ke_hoach_id, thoi_diem DESC);
